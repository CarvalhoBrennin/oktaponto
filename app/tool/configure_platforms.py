#!/usr/bin/env python3
"""Patch generated Flutter platform projects to the OktaPonto mobile baseline.

The mobile folders are generated by Flutter 3.47.2 so this script keeps only
project-specific settings in source control while making bootstrap repeatable.
"""
from __future__ import annotations

import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]


def write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")


def version_tuple(value: str) -> tuple[int, ...]:
    return tuple(int(part) for part in re.findall(r"\d+", value)[:3])


manifest = root / "android/app/src/main/AndroidManifest.xml"
if manifest.exists():
    text = manifest.read_text(encoding="utf-8")
    permission = '<uses-permission android:name="android.permission.RECEIVE_BOOT_COMPLETED"/>'
    if permission not in text:
        text = re.sub(
            r"(<manifest\b[^>]*>)",
            r"\1\n    " + permission,
            text,
            count=1,
        )
    text = re.sub(r'android:label="oktaponto"', 'android:label="OktaPonto"', text)
    receiver = '''
        <receiver android:exported="false" android:name="com.dexterous.flutterlocalnotifications.ScheduledNotificationReceiver" />
        <receiver android:exported="false" android:name="com.dexterous.flutterlocalnotifications.ScheduledNotificationBootReceiver">
            <intent-filter>
                <action android:name="android.intent.action.BOOT_COMPLETED"/>
                <action android:name="android.intent.action.MY_PACKAGE_REPLACED"/>
                <action android:name="android.intent.action.QUICKBOOT_POWERON"/>
                <action android:name="com.htc.intent.action.QUICKBOOT_POWERON"/>
            </intent-filter>
        </receiver>
'''
    if "ScheduledNotificationReceiver" not in text:
        text = text.replace("</application>", receiver + "    </application>")
    write(manifest, text)


gradle = root / "android/app/build.gradle.kts"
if gradle.exists():
    text = gradle.read_text(encoding="utf-8")
    application_id_pattern = r'applicationId\s*=\s*"[^"]+"'
    if not re.search(application_id_pattern, text):
        raise RuntimeError("Generated Android applicationId was not found.")
    text = re.sub(
        application_id_pattern,
        'applicationId = "com.oktaponto.app"',
        text,
        count=1,
    )
    text = text.replace("compileSdk = flutter.compileSdkVersion", "compileSdk = 36")
    text = text.replace("minSdk = flutter.minSdkVersion", "minSdk = 24")
    text = text.replace("targetSdk = flutter.targetSdkVersion", "targetSdk = 36")
    text = re.sub(
        r"sourceCompatibility\s*=\s*JavaVersion\.VERSION_\d+",
        "sourceCompatibility = JavaVersion.VERSION_17",
        text,
    )
    text = re.sub(
        r"targetCompatibility\s*=\s*JavaVersion\.VERSION_\d+",
        "targetCompatibility = JavaVersion.VERSION_17",
        text,
    )
    text = re.sub(
        r"jvmTarget\s*=\s*JavaVersion\.VERSION_\d+\.toString\(\)",
        "jvmTarget = JavaVersion.VERSION_17.toString()",
        text,
    )
    if "isCoreLibraryDesugaringEnabled" not in text:
        text = text.replace(
            "compileOptions {",
            "compileOptions {\n        isCoreLibraryDesugaringEnabled = true",
            1,
        )
    if "multiDexEnabled = true" not in text:
        text = text.replace("defaultConfig {", "defaultConfig {\n        multiDexEnabled = true", 1)
    dep = 'coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:2.1.4")'
    if dep not in text:
        text += f"\n\ndependencies {{\n    {dep}\n}}\n"
    write(gradle, text)


wrapper = root / "android/gradle/wrapper/gradle-wrapper.properties"
if wrapper.exists():
    text = wrapper.read_text(encoding="utf-8")
    text = re.sub(
        r"gradle-[0-9.]+-(bin|all)\.zip",
        lambda match: f"gradle-9.3.1-{match.group(1)}.zip",
        text,
    )
    write(wrapper, text)


settings = root / "android/settings.gradle.kts"
if settings.exists():
    text = settings.read_text(encoding="utf-8")
    pattern = re.compile(r'id\("com\.android\.application"\) version "([^"]+)" apply false')
    match = pattern.search(text)
    if match and version_tuple(match.group(1)) < version_tuple("8.11.1"):
        text = pattern.sub(
            'id("com.android.application") version "8.11.1" apply false',
            text,
            count=1,
        )
    write(settings, text)


podfile = root / "ios/Podfile"
if podfile.exists():
    text = podfile.read_text(encoding="utf-8")
    lines = text.splitlines()
    replaced = False
    for index, line in enumerate(lines):
        if line.strip().startswith("platform :ios"):
            lines[index] = "platform :ios, '15.0'"
            replaced = True
            break
    if not replaced:
        lines.insert(0, "platform :ios, '15.0'")
    write(podfile, "\n".join(lines) + "\n")


pbxproj = root / "ios/Runner.xcodeproj/project.pbxproj"
if pbxproj.exists():
    text = pbxproj.read_text(encoding="utf-8")
    text = re.sub(
        r"IPHONEOS_DEPLOYMENT_TARGET = [0-9.]+;",
        "IPHONEOS_DEPLOYMENT_TARGET = 15.0;",
        text,
    )
    write(pbxproj, text)


info_plist = root / "ios/Runner/Info.plist"
if info_plist.exists():
    text = info_plist.read_text(encoding="utf-8")
    text = text.replace("<string>OktaPonto</string>", "<string>OktaPonto</string>")
    text = text.replace("<string>oktaponto</string>", "<string>OktaPonto</string>")
    write(info_plist, text)


app_delegate = root / "ios/Runner/AppDelegate.swift"
if app_delegate.exists():
    text = app_delegate.read_text(encoding="utf-8")
    if "import UserNotifications" not in text:
        text = text.replace("import Flutter", "import Flutter\nimport UserNotifications")
    marker = "GeneratedPluginRegistrant.register(with: self)"
    delegate = "UNUserNotificationCenter.current().delegate = self"
    if marker in text and delegate not in text:
        text = text.replace(marker, delegate + "\n    " + marker)
    write(app_delegate, text)
